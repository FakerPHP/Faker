Pemberontakan Hang Jebat dan Pertarungan Tujuh Hari

Selepas Hang Tuah difitnah dan disangka telah dihukum mati, Sultan Melaka melantik Hang Jebat sebagai Laksamana yang baharu dan menganugerahkan kepadanya Keris Taming Sari, lambang kepimpinan dan keberanian panglima tertinggi istana.
Sekian lama, Hang Jebat berasa amat kecewa dan atas nasib yang menimpa sahabatnya Hang Tuah, yang menurutnya telah dianiaya tanpa pengadilan yang secukupnya. Dalam versi Hikayat Hang Tuah, Hang Jebat memberontak untuk menentang kezaliman sultan menggunakan kedudukan dan pengaruhnya sebagai Laksamana untuk menguasai istana. Namun dalam versi Sejarah Melayu, watak yang memulakan penderhakaan itu ialah Hang Kasturi.
