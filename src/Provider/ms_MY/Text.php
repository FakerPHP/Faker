Ketika ekspedisi mendaki Gunung Ledang untuk meminang Puteri Gunung Ledang, Hang Tuah tidaklah merasa sangat kecewa hingga ghaib di Sungai Melaka akibat gagal meneruskan pendakian ke puncak Gunung Ledang. Hang Tuah masih lagi hidup hingga beliau meninggal dunia setelah sekembali menantunya, Hang Nadim dari Benua Keling. Hang Tuah telah dimakamkan dengan penuh adat istiadat di Tanjung Keling, Melaka oleh Sultan Mahmud Shah. Hingga sekarang makam tersebut masih lagi wujud dan terjaga dengan baik oleh kerajaan negeri Melaka. Jawatan Laksamana kemudiannya disandang oleh menantunya sendiri, Khoja Hassan. Selepas Laksamana Khoja Hassan meninggal dunia, jawatan Laksamana disandang pula oleh Hang Nadim, namun ketika itu Kesultanan Melaka telah berpindah ke Johor.
Satu lagi perkara yang perlu diperhatikan, bukanlah Hang Tuah yang melarikan Tun Teja dari Pahang sebagaimana di dalam Hikayat Hang Tuah. Peristiwa tersebut sebenarnya berlaku selepas Hang Tuah meninggal dunia. Dicatatkan yang melarikan Tun Teja adalah Hang Nadim, iaitu menantu Hang Tuah.

Peranan dalam Kesultanan Melaka

Hang Tuah dilantik sebagai Laksamana kerana keberanian dan kebijaksanaannya dalam mengurus urusan istana serta hubungan diplomatik dengan kuasa asing seperti Dinasti Ming di China dan Kerajaan Majapahit di Jawa. Beliau dikatakan pernah mengetuai misi ke Majapahit dan membawa pulang puteri diraja Hang Li Po untuk diperisterikan oleh Sultan Mansur Shah, walaupun kebenaran sejarah peristiwa ini masih diperdebatkan.

Perseteruan dengan Hang Jebat

Salah satu kisah paling terkenal ialah pertembungan antara Hang Tuah dan sahabatnya Hang Jebat. Hang Jebat bangkit menentang sultan setelah Hang Tuah dihukum mati tanpa bicara. Namun, apabila Hang Tuah dibebaskan, beliau diperintahkan untuk menumpaskan Hang Jebat. Pertarungan ini berakhir dengan kematian Hang Jebat, melambangkan dilema antara kesetiaan terhadap raja dan keadilan kepada sahabat.

Legenda dan Simbolisme

Dalam budaya Melayu, Hang Tuah dianggap sebagai simbol kesetiaan mutlak kepada pemerintah dan keutuhan nilai bangsa. Ungkapan terkenal yang dikaitkan dengannya ialah "Takkan Melayu hilang di dunia, selagi Melayu berpegang kepada agama", yang menjadi pepatah nasionalisme Melayu moden.
Watak Hang Tuah turut menjadi ikon dalam kesusasteraan, teater, filem dan wacana politik Melayu, menggambarkan ketegangan antara taat setia dan keadilan sosial.

