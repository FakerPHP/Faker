Biografi

Menurut rekod dan tradisi lisan, Hang Tuah dilahirkan di Pulau Bintan antara tahun 1431 hingga 1444. Bapanya bernama Hang Mahmud, manakala ibunya ialah Dang Merdu Wati. Sejak muda, Hang Tuah menunjukkan kepimpinan dan ketajaman akal. Hang Tuah mengetuai rombongan bersama empat sahabat karibnya: Hang Jebat, Hang Kasturi, Hang Lekir dan Hang Lekiu untuk berguru dengan seorang Guru Silat di Gunung Ledang.
Setelah menamatkan pengajian, mereka berlima kembali ke Melaka. Dalam perjalanan pulang, mereka terserempak dengan Bendahara Tun Perak yang telah dikepung oleh sekumpulan penjahat. Hang Tuah dan empat sahabatnya menunjukkan keberanian apabila mereka memilih untuk menyelamatkan Tun Perak dan bertarung dengan kumpulan penjahat tersebut. Ketangkasan dan kecekapan mereka bertarung dengan kumpulan penjahat itu telah menarik perhatian Tun Perak. Setelah berjaya menumpaskan kumpulan tersebut, Hang Tuah dan empat orang sahabatnya dijemput untuk menghadap Sultan Melaka. Mereka berlima akhirnya dilantik sebagai Hulubalang untuk berkhidmat di bawah naungan Sultan Melaka.
