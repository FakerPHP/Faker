Tragedi ini terus menjadi lambang pengorbanan dalam budaya Melayu, memperlihatkan bahawa dalam setiap perjuangan, keadilan dan kesetiaan hanya bernilai apabila disertai dengan iman dan keikhlasan.

Hang Tuah menurut catatan sejarah Sulalatus Salatin

Terdapat perbezaan penceritaan mengenai sejarah Hang Tuah antara Hikayat Hang Tuah dan Sulalatus Salatin. Gambaran Hang Tuah yang dicatatkan oleh Tun Seri Lanang dalam Sulalatus Salatin dilihat lebih realistik serta tidak sarat dengan unsur mistik. Dalam Sulalatus Salatin, nama sebenar Hang Tuah dicatatkan sebagai Daeng Mempawah. Beliau merupakan anak kepada Raja Bajung (sebutan asal dalam bahasa Sulawesi ialah Bajeng) dan berasal dari wilayah Gowa, Makassar, Sulawesi.
Hang Tuah telah dikurniakan oleh Raja Gowa kepada rombongan diplomatik Melaka yang diketuai oleh Seri Bija Pikrama dan Tun Sura Diraja, sebagai hadiah kepada Sultan Mansur Shah, Sultan Melaka pada ketika itu. Ketika dikurniakan kepada rombongan Melaka, Hang Tuah masih berusia sekitar 12 tahun. Walaupun masih muda, beliau dikisahkan pernah membunuh dua orang yang mengamuk di negerinya.
Nama "Hang Tuah" diberikan oleh Sultan Mansur Shah setelah baginda berkenan melihat beliau. Hang Tuah kemudian dikurniakan keris yang bernama Keris Tempa Melaka (bukan keris Taming Sari). Sepanjang berada di Melaka, Hang Tuah berguru dengan hulubalang-hulubalang yang ada di Melaka, bukan dengan Adi Putera di Gunung Ledang seperti di dalam hikayat yang masyhur itu. "Perhangan" yang kita sedia maklum adalah lima orang tetapi sebenarnya di dalam Sejarah Melayu (Sulalatus Salatin), Sultan Mansur telah memilih lapan orang "Hang" sebelum kedatangan Hang Tuah, iaitu:
