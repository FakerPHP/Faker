Maka dengan kedatangan Hang Tuah, "Perhangan" (pahlawan Melaka) menjadi sembilan orang semuanya. Mereka semuanya saling bermuafakat dan berkasih sayang. Hang Tuah adalah pahlawan yang paling handal di antara sembilan orang "Hang" ini.
Hang Tuah dikenali sebagai seorang yang rupawan, cerdik, perkasa, mempunyai hikmat dan berani. Apabila ada orang yang mengamuk di dalam Melaka dan tidak ada sesiapa yang mampu mengawal amukan tersebut maka Hang Tuah akan dititahkan oleh Sultan untuk mengatasinya. Dikatakan bahawa Hang Tuah pernah membunuh 74 orang yang mengamuk di Melaka. Pemuda-pemuda di Melaka menggelarnya Laksamana kerana apabila Hang Tuah bergurau dengan rakan-rakannya, beliau akan menyinsing lengannya dan berkata: "Laksamana akan lawanku". Sejak dari itu para pemuda memanggilnya dengan Laksamana hingga akhirnya sultan juga terikut-ikut memanggilnya Laksamana.
Pada suatu hari ada seorang dari suku Jawa mengamuk kerana berasa malu diejek oleh para pemuda Melaka. Ramai yang telah dibunuh oleh orang Jawa tersebut dan tidak ada sesiapa yang mampu menghalanginya. Sultan Mansur Shah kemudian menghantar Hang Tuah untuk menyelesaikannya dan akhirnya orang yang mengamuk itu berjaya dibunuh. Dengan kejayaan itu, Sultan terus melantik Hang Tuah menjadi Laksamana. Digambarkan juga di dalam Sulalatus Salatin akan ketampanan Hang Tuah. Ketika berada di Majapahit, Hang Tuah telah menjadi kegilaan para wanita Jawa sama ada gadis sunti atau isteri orang. Dikatakan jika seorang isteri sedang berada dalam dakapan suaminya sekalipun pasti akan terkejut dan terus keluar untuk melihat Hang Tuah.
Ketika pertarungan dengan Hang Jebat, Hang Tuah dalam keadaan tubuh yang sangat kurus. Berjalan pun terketar-ketar kerana beliau dipasung dalam tempoh yang lama oleh Seri Nara Diraja di Dusun akibat kesalahan berzina dengan Dayang Istana. Hang Tuah berjaya menewaskan Hang Jebat kerana kepintarannya memperdaya Hang Jebat. Ketika keris beliau terlekat di dinding, beliau meminta belas kasihan daripada Hang Jebat agar memberikannya peluang untuk mencabut kembali kerisnya. Hal tersebut berlaku selama dua tiga kali. Tetapi apabila keris Hang Jebat tersangkut ke dinding, cepat-cepat beliau menikam Hang Jebat. Apa yang perlu diperhatikan, tidak ada diceritakan bahawa Hang Tuah dan Hang Jebat bertarung di atas talam kerana para pengawal menjolok dengan lembing dari bawah istana. Juga tidak ada perebutan keris Taming Sari yang mana sesiapa yang memiliki keris tersebut akan menjadi kebal. Malah Keris Taming Sari itu juga tidak wujud dalam Sulalatus Salatin.
